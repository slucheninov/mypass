import XCTest
@testable import MyPassKit

/// Cross-compatibility with real KeePassXC/pykeepass files.
///
/// The fixtures are generated with `pykeepass` (a Python library that writes
/// real KeePass files; install it with pip and build each file with
/// `PyKeePass`/`create_database` plus `add_entry`). The shared password is the
/// public test value in `referencePassword` below, never a real credential. The
/// GZip fixtures (`argon2id-aes256-gzip`, `chacha20-argon2id-gzip`) and the
/// Argon2d fixture (`argon2d-aes256-gzip`) were generated with
/// pykeepass's own realistic defaults — a 32-byte Argon2 salt and
/// parallelism 2 — rather than any reduced-parameter workaround, and they
/// open end to end through `KdbxDatabase.open` (see
/// `testArgon2idGzipFixturesOpenAndRecoverCorrectData` and
/// `testArgon2dGzipFixtureOpensAndRecoversCorrectData` below).
final class KdbxCrossCompatibilityTests: XCTestCase {
    private static let referencePassword = "TestMasterPass123"

    // MARK: - Gzip framing correctness
    //
    // Real fixture files already reach the gzip code path end-to-end through
    // `KdbxDatabase.open` (see `testArgon2idGzipFixturesOpenAndRecoverCorrectData`
    // below, which asserts on their recovered contents). The direct,
    // byte-for-byte checks here against the system `gzip`/`gunzip` binaries
    // are kept alongside that because they verify something an end-to-end
    // open cannot: that our framing is the real gzip container (magic bytes,
    // CRC32/ISIZE trailer) and not merely something our own `gzip`/`gunzip`
    // agree with each other about — the standard this task's original brief
    // asked for ("verify your output is decompressible by the system
    // gunzip/zcat command").

    /// `gzip(_:)` must start with the real gzip magic bytes (`1F 8B`), not
    /// raw zlib/deflate framing (which starts with `78 xx`).
    func testGzipOutputHasRealGzipMagicBytes() throws {
        let plaintext = Data("Hello, KeePassXC!".utf8)
        let compressed = try KdbxDatabase.gzip(plaintext)
        XCTAssertGreaterThanOrEqual(compressed.count, 2)
        XCTAssertEqual(compressed[compressed.startIndex], 0x1F)
        XCTAssertEqual(compressed[compressed.index(after: compressed.startIndex)], 0x8B)
    }

    /// Our `gzip(_:)` output must be decompressible by the system `gunzip`.
    func testOwnGzipOutputIsDecompressibleBySystemGunzip() throws {
        let plaintext = Data("The quick brown fox jumps over the lazy dog.\n".utf8)
        let compressed = try KdbxDatabase.gzip(plaintext)

        let tempDir = FileManager.default.temporaryDirectory
        let gzPath = tempDir.appendingPathComponent(UUID().uuidString + ".gz")
        try compressed.write(to: gzPath)
        defer { try? FileManager.default.removeItem(at: gzPath) }

        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/gunzip")
        process.arguments = ["-c", gzPath.path]
        let outputPipe = Pipe()
        process.standardOutput = outputPipe
        try process.run()
        let decompressed = outputPipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()

        XCTAssertEqual(process.terminationStatus, 0, "system gunzip failed to decompress our gzip output")
        XCTAssertEqual(decompressed, plaintext)
    }

    /// Our `gunzip(_:)` must correctly decompress a real gzip file produced
    /// by the system `gzip` command (not just our own output).
    func testGunzipDecompressesSystemGzipOutput() throws {
        let plaintext = Data("Round-trip through the system gzip binary, not just our own code.\n".utf8)

        let tempDir = FileManager.default.temporaryDirectory
        let plainPath = tempDir.appendingPathComponent(UUID().uuidString + ".txt")
        try plaintext.write(to: plainPath)
        defer {
            try? FileManager.default.removeItem(at: plainPath)
            try? FileManager.default.removeItem(at: plainPath.appendingPathExtension("gz"))
        }

        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/gzip")
        process.arguments = ["-k", "-f", plainPath.path]
        try process.run()
        process.waitUntilExit()
        XCTAssertEqual(process.terminationStatus, 0, "system gzip failed to compress the fixture text")

        let systemGzipData = try Data(contentsOf: plainPath.appendingPathExtension("gz"))
        XCTAssertEqual(systemGzipData[systemGzipData.startIndex], 0x1F)
        XCTAssertEqual(systemGzipData[systemGzipData.index(after: systemGzipData.startIndex)], 0x8B)

        let decompressed = try KdbxDatabase.gunzip(systemGzipData)
        XCTAssertEqual(decompressed, plaintext)
    }

    // MARK: - Real KeePassXC reference fixtures

    /// The AES-KDF fixture. This is the
    /// critical cross-compatibility proof for AES-KDF read support: a real
    /// KDBX4 file generated by `pykeepass` (regenerate it with
    /// `kdf_uuid="aeskdf"`, `R=60000`, cipher
    /// AES256, no compression) opened end-to-end through
    /// `KdbxDatabase.open`, with the recovered entry data checked
    /// byte-for-byte against what the generation script wrote
    /// (`add_entry(kp.root_group, "Test Entry", "testuser", "hunter2")`).
    /// A wrong AES-KDF block arrangement (e.g. CBC instead of ECB, or a
    /// different per-round buffer split) would still be internally
    /// self-consistent but would fail to derive the correct `masterKey`,
    /// so this test — unlike a self-generated round trip — actually proves
    /// the algorithm matches KeePassXC's.
    func testAesKdfFixtureOpensAndRecoversCorrectData() throws {
        guard let url = Bundle.module.url(forResource: "aeskdf-aes256-none", withExtension: "kdbx", subdirectory: "Fixtures") else {
            throw XCTSkip("Fixture aeskdf-aes256-none.kdbx is missing")
        }
        let data = try Data(contentsOf: url)
        let database = try KdbxDatabase.open(data: data, password: Self.referencePassword)

        XCTAssertEqual(database.rootGroup.entries.count, 1)
        let entry = try XCTUnwrap(database.rootGroup.entries.first)
        XCTAssertEqual(entry.fields.first(where: { $0.key == "Title" })?.value, "Test Entry")
        XCTAssertEqual(entry.fields.first(where: { $0.key == "UserName" })?.value, "testuser")
        XCTAssertEqual(entry.fields.first(where: { $0.key == "Password" })?.value, "hunter2")
    }

    /// Real KeePassXC/pykeepass-generated Argon2id+GZip fixtures, generated
    /// with pykeepass's own realistic parameters (M=64 MiB, I=14, P=2, 32-byte
    /// salt) instead of the earlier P=1 workaround. Renamed from
    /// `testArgon2idGzipFixturesFailDueToSaltLengthLimitationNotGzip` now that
    /// the salt-length limitation it used to pin no longer exists.
    func testArgon2idGzipFixturesOpenAndRecoverCorrectData() throws {
        let fixtureNames = ["argon2id-aes256-gzip", "chacha20-argon2id-gzip"]
        for name in fixtureNames {
            guard let url = Bundle.module.url(forResource: name, withExtension: "kdbx", subdirectory: "Fixtures") else {
                throw XCTSkip("Fixture \(name).kdbx is missing")
            }
            let data = try Data(contentsOf: url)
            let database = try KdbxDatabase.open(data: data, password: Self.referencePassword)
            XCTAssertEqual(database.rootGroup.entries.count, 1, "for \(name)")
            let entry = try XCTUnwrap(database.rootGroup.entries.first, "for \(name)")
            XCTAssertEqual(entry.fields.first(where: { $0.key == "Title" })?.value, "Test Entry", "for \(name)")
            XCTAssertEqual(entry.fields.first(where: { $0.key == "UserName" })?.value, "testuser", "for \(name)")
            XCTAssertEqual(entry.fields.first(where: { $0.key == "Password" })?.value, "hunter2", "for \(name)")
        }
    }

    /// New in this task: a real pykeepass-generated Argon2d fixture (produced
    /// with zero KDF overrides — pykeepass's own un-overridden default is
    /// Argon2d, matching KeePass's historical default before KeePassXC
    /// switched to Argon2id — see this task's writeup). Proves the Argon2d
    /// branch added in Task 5 works end to end against a real file, not just
    /// a known-answer vector.
    func testArgon2dGzipFixtureOpensAndRecoversCorrectData() throws {
        guard let url = Bundle.module.url(forResource: "argon2d-aes256-gzip", withExtension: "kdbx", subdirectory: "Fixtures") else {
            throw XCTSkip("Fixture argon2d-aes256-gzip.kdbx is missing")
        }
        let data = try Data(contentsOf: url)
        let database = try KdbxDatabase.open(data: data, password: Self.referencePassword)
        XCTAssertEqual(database.rootGroup.entries.count, 1)
        let entry = try XCTUnwrap(database.rootGroup.entries.first)
        XCTAssertEqual(entry.fields.first(where: { $0.key == "Title" })?.value, "Test Entry")
        XCTAssertEqual(entry.fields.first(where: { $0.key == "UserName" })?.value, "testuser")
        XCTAssertEqual(entry.fields.first(where: { $0.key == "Password" })?.value, "hunter2")
    }

    // MARK: - Self-consistent round trip (this package's own KDF params)

    /// Full `save` → `open` round trip using this package's own `save()`
    /// (32-byte salt, parallelism 2, Argon2id, GZip compression) — this
    /// exercises the real gzip container end-to-end through the whole
    /// pipeline (HMAC block stream, cipher, gzip, inner header, XML).
    /// Cross-compatibility with real KeePassXC files is already proven
    /// above, by `testArgon2idGzipFixturesOpenAndRecoverCorrectData` and
    /// `testArgon2dGzipFixtureOpensAndRecoversCorrectData` against real
    /// pykeepass-generated fixtures; this test instead pins that this
    /// package's own writer and reader stay consistent with each other.
    func testWriteThenOpenWithGzipRoundTrips() throws {
        let root = KdbxGroup(uuid: UUID(), name: "Root", iconID: 0, creationTime: Date(), lastModificationTime: Date(), locationChanged: Date(), entries: [], subgroups: [])
        let database = KdbxDatabase(rootGroup: root, deletedObjects: [])
        let saved = try database.save(password: "test-pass", cipher: .aes256, compression: .gzip)

        let reopened = try KdbxDatabase.open(data: saved, password: "test-pass")
        XCTAssertEqual(reopened.rootGroup.name, "Root")
    }
}
